"use strict";
const assert = require("node:assert/strict");
const { DEFAULTS, PRICE_DEFAULTS, lifecycleCost, validatePlan, validatePriceConfig, transformPrice, createDemo, chartSvg } = require("./app.js");
const close = (a, b) => assert.ok(Math.abs(a - b) < 1e-9, `${a} != ${b}`);
const initial = lifecycleCost(DEFAULTS);
close(initial.usableKwh, 160.5632);
close(initial.lifetimeCycles, 3750);
close(initial.lifetimeOutputKwh, 160.5632 * 3750 * 0.9 * 0.96);
close(initial.fullCostCtKwh, 40000 / initial.lifetimeOutputKwh * 100);
close(initial.roundTripEfficiency, 0.912);
assert.equal(initial.limitingFactor, "Kalenderlebensdauer");
const cycleLimited = lifecycleCost({ ...DEFAULTS, cycles: 1000 });
assert.equal(cycleLimited.limitingFactor, "Zyklenlebensdauer");
close(cycleLimited.lifetimeCycles, 1000);
close(lifecycleCost({ ...DEFAULTS, chargeEfficiency: 50 }).lifetimeOutputKwh, initial.lifetimeOutputKwh);
close(lifecycleCost({ ...DEFAULTS, marginalWear: 3 }).fullCostCtKwh, initial.fullCostCtKwh);
assert.throws(() => lifecycleCost({ ...DEFAULTS, minSoc: 90, maxSoc: 90 }), /Ladezustand/);
assert.throws(() => lifecycleCost({ ...DEFAULTS, residual: 50000 }), /Restwert/);
assert.throws(() => lifecycleCost({ ...DEFAULTS, capacity: "" }), /ausfüllen/);
assert.throws(() => lifecycleCost({ ...DEFAULTS, years: Infinity }), /endliche/);
const demo = createDemo();
assert.equal(demo.slots.length, 96);
for (const slot of demo.slots) {
  assert.ok(slot.soc_pct >= 10 - 1e-8 && slot.soc_pct <= 90 + 1e-8);
  assert.ok(slot.battery_power_kw <= 50 + 1e-8 && slot.battery_power_kw >= -35 - 1e-8);
  close(slot.grid_power_kw, slot.load_kw + slot.battery_power_kw - slot.pv_kw);
}
const total = demo.slots.reduce((sum, s) => sum + s.cost_eur, 0);
const valid = { ...demo, total_cost_eur: total, baseline_cost_eur: total + 2, savings_eur: 2 };
assert.equal(validatePlan(valid).slots.length, 96);
const corrupt = structuredClone(valid);
corrupt.slots[4].grid_power_kw += 100;
assert.throws(() => validatePlan(corrupt), /Leistungsbilanz/);
assert.throws(() => validatePlan({ ...valid, savings_eur: 500 }), /Einsparung/);
const noZone = structuredClone(valid);
noZone.slots[0].start = "2026-11-03T00:00:00";
assert.throws(() => validatePlan(noZone), /Zeitzone/);
const gap = structuredClone(valid);
gap.slots[1].start = gap.slots[2].start;
assert.throws(() => validatePlan(gap), /lückenlos/);
const image = chartSvg(demo.slots);
assert.ok(image.startsWith("<svg") && !image.includes("NaN") && !image.includes("Infinity"));
const prices = validatePriceConfig(PRICE_DEFAULTS);
assert.equal(Object.keys(prices).length, 14);
assert.equal(prices.import_price_mode, "forecast");
const independent = validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "entity", import_price_entity: "sensor.bezug_prognose", import_price_unit: "ct_kwh", export_price_mode: "fixed", export_price_unit: "ct_kwh", export_fixed_price: 8.2 });
assert.equal(independent.import_price_entity, "sensor.bezug_prognose");
assert.equal(independent.export_fixed_price, 8.2);
close(transformPrice(100, "eur_mwh", 1.19, .02), .139);
close(transformPrice(8.2, "ct_kwh"), .082);
close(transformPrice(-50, "eur_mwh", 1, -.01), -.06);
const smard = validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "smard", import_price_unit: "ct_kwh", import_price_adder_eur_kwh: .12 });
assert.equal(smard.import_price_unit, "eur_mwh");
assert.equal(smard.export_price_mode, "forecast");
assert.equal(smard.export_price_adder_eur_kwh, 0);
const urlConfig = validatePriceConfig({ ...PRICE_DEFAULTS, export_price_mode: "url", export_price_url: "https://example.invalid/prices?q=%3Cscript%3E", export_price_unit: "eur_mwh" });
assert.equal(urlConfig.export_price_url, "https://example.invalid/prices?q=%3Cscript%3E");
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "url", import_price_url: "javascript:alert(1)" }), /HTTP/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "url", import_price_url: "file:///secret" }), /HTTP/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "url", import_price_url: "https://user:secret@example.invalid" }), /Zugangsdaten/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "entity", import_price_entity: '<img src=x onerror="alert(1)">' }), /Entität/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "__proto__" }), /Preisquelle/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_unit: "USD" }), /Einheit/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_multiplier: -1 }), /negativ/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_multiplier: Infinity }), /endliche/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_multiplier: "   " }), /endliche/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_fixed_price: true }), /endliche/);
assert.throws(() => validatePriceConfig({ ...PRICE_DEFAULTS, import_price_mode: "fixed", import_fixed_price: 1e308, import_price_multiplier: 1e308 }), /Zahlenbereich/);
const whitelisted = validatePriceConfig({ ...PRICE_DEFAULTS, unwanted: "<script>alert(1)</script>" });
assert.equal(Object.hasOwn(whitelisted, "unwanted"), false);
assert.equal(validatePriceConfig({ ...PRICE_DEFAULTS, import_price_entity: "unused", import_price_url: "javascript:unused" }).import_price_url, "");
console.log("Preview arithmetic, plan validation, demo balance, chart generation and price configuration checks passed.");
